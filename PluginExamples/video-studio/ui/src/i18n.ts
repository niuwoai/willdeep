export type Translator = (key: string, values?: Record<string, string | number>) => string;

export function localeFromContext(value?: string): 'zh-Hans' | 'en' {
  return value?.toLowerCase().startsWith('zh') ? 'zh-Hans' : 'en';
}

export function createTranslator(locale: 'zh-Hans' | 'en'): Translator {
  const dictionary = locale === 'zh-Hans' ? zhHans : en;
  return (key, values = {}) => {
    const template = dictionary[key] ?? en[key] ?? key;
    return Object.entries(values).reduce(
      (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
      template,
    );
  };
}
